/** The logo for a catalogue icon name, or a neutral initial when there's none. */
export default function BrandIcon({ name, label = "", size = 20 }) {
  const entry = ICONS[name];
  if (!entry) {
    return (
      <span className="np-logo-fallback" style={{ width: size, height: size, fontSize: Math.round(size * 0.55) }} aria-hidden="true">
        {(label || "?").trim().charAt(0).toUpperCase()}
      </span>
    );
  }
  const [Icon, token] = entry;
  return <Icon size={size} aria-hidden="true" style={{ color: token ? `var(${token})` : "currentColor", flexShrink: 0 }} />;
}
