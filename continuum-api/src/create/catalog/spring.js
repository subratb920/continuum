// src/create/catalog/spring.js
//
// Spring Boot: the variant's options, details and dependencies come from
// Spring Initializr's live metadata (templates/spring.js), so the wizard
// offers exactly what start.spring.io offers. refreshSpring() fills this
// kind in; until it has loaded once, the kind has no variants (and is hidden).

import { field } from "../fields.js";
import { inVersionRange, springMetadata, springTemplate } from "../templates/spring.js";

/** Brand icons for well-known Initializr dependencies (others show their initial) */
const ICONS = {
  web: "SiSpring",
  webflux: "SiSpring",
  "data-jpa": "SiSpring",
  postgresql: "SiPostgresql",
  mysql: "SiMysql",
  "data-mongodb": "SiMongodb",
  "data-mongodb-reactive": "SiMongodb",
  "data-redis": "SiRedis",
  "data-redis-reactive": "SiRedis",
  "docker-compose": "SiDocker",
  graphql: "SiGraphql",
  sqlite: "SiSqlite",
  kotlin: "SiKotlin",
};

const slug = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const spring = {
  id: "spring",
  name: "Spring Boot",
  icon: "SiSpringboot",
  description: "Production-ready Java and Kotlin services, from Spring Initializr.",
  groups: [],
  variants: [],
  dependencies: [],
};

/** Rebuilds the kind from Initializr's metadata (cached hourly there). Never throws. */
export async function refreshSpring() {
  let m;
  try {
    m = await springMetadata();
  } catch {
    return spring; // unreachable and never loaded: the kind stays hidden
  }
  const choice = (key, label, keep = () => true) => ({
    id: key,
    label,
    type: "choice",
    values: m[key].values.filter(keep).map((v) => ({ id: v.id, label: v.name })),
    default: m[key].default,
  });
  const type = choice("type", "Build", (v) => !v.id.endsWith("-build")); // whole projects, not just a build file
  type.values = type.values.map((v) => ({ ...v, icon: v.id.startsWith("maven") ? "SiApachemaven" : v.id.endsWith("kotlin") ? "SiKotlin" : "SiGradle" }));
  const language = choice("language", "Language");
  language.values = language.values.map((v) => ({ ...v, icon: { java: "SiOpenjdk", kotlin: "SiKotlin" }[v.id] }));
  const bootVersion = choice("bootVersion", "Spring Boot");
  const boots = bootVersion.values.map((v) => v.id);

  spring.groups = m.dependencies.values.map((g) => ({ id: slug(g.name), name: g.name }));
  spring.dependencies = m.dependencies.values.flatMap((g) =>
    g.values.map((d) => {
      const compatible = d.versionRange ? boots.filter((b) => inVersionRange(b, d.versionRange)) : null;
      return {
        id: d.id,
        name: d.name,
        description: d.description ?? "",
        group: slug(g.name),
        icon: ICONS[d.id] ?? null,
        docs: d._links?.reference?.href?.replace("{bootVersion}", m.bootVersion.default) ?? null,
        appliesTo: "*",
        ...(compatible && compatible.length < boots.length && { when: { bootVersion: compatible }, versionRange: d.versionRange }),
      };
    })
  );
  spring.variants = [
    {
      id: "boot",
      name: "Spring Boot",
      icon: "SiSpringboot",
      description: "A Spring Boot application, generated by start.spring.io with your choices.",
      options: [type, language, bootVersion, choice("javaVersion", "Java"), choice("packaging", "Packaging")],
      details: [
        field("group", "Group", "javaGroup", { default: m.groupId.default, placeholder: m.groupId.default }),
        field("artifact", "Artifact", "javaArtifact", { default: m.artifactId.default, placeholder: m.artifactId.default, help: "Also the folder's name" }),
        field("name", "Name", "javaArtifact", { required: false, placeholder: m.artifactId.default, derive: { from: ["artifact"], transform: "same" } }),
        field("description", "Description", "text", { required: false, placeholder: "Demo project for Spring Boot" }),
        field("packageName", "Package name", "javaPackage", {
          required: false,
          placeholder: m.packageName.default,
          derive: { from: ["group", "artifact"], transform: "javaPackage" },
        }),
      ],
      template: springTemplate,
    },
  ];
  return spring;
}

export default spring;
